-- Documentation for Custom Position and Custom Odds
-- The 'bids' table stores custom positions and odds in 'position_prediction' TEXT column
-- Example values:
--   '1' (Preset: 1st place, default 1.5x)
--   '2-3' (Preset: 2nd-3rd place, default 1.4x)
--   '5 (2.5x)' (Custom position 5 with 2.5x multiplier)
--   '2-5 (1.8x)' (Custom position range 2-5 with 1.8x multiplier)
--
-- No schema changes are required as position_prediction is already TEXT.
